def to_trad(text):
    if not text:
        return ""
    # 1. Term replacement
    res = text
    for s, t in TERM_REPLACEMENTS:
        res = res.replace(s, t)
    # 2. Char replacement
    out = []
    for c in res:
        out.append(SIMP_TO_TRAD_CHARS.get(c, c))
    return "".join(out)

def escape_xml(val):
    if not val:
        return ""
    val = val.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    parts = val.split(r"\'")
    val = r"\'".join([p.replace("'", r"\'") for p in parts])
    parts = val.split(r'\"')
    val = r'\"'.join([p.replace('"', r'\"') for p in parts])
    return val

