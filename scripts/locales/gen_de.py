def escape_xml(val):
    if not val:
        return ""
    val = val.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    parts = val.split(r"\'")
    val = r"\'".join([p.replace("'", r"\'") for p in parts])
    parts = val.split(r'\"')
    val = r'\"'.join([p.replace('"', r'\"') for p in parts])
    return val

